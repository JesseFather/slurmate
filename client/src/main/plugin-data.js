'use strict';
/**
 * plugin-data.js —— 插件**运行时数据**的身份：一份数据存在哪儿、和谁共用。
 *
 * ── 它要解决什么 ────────────────────────────────────────────────────────────
 *
 * 插件在运行中会产生**用户数据**，最实在的一个例子是 code-server 的编辑器布局与
 * 登录 cookie（丢了要重新摆一遍）。这类数据必须落在一个**跟着插件走、而不是跟着
 * 会话走**的地方 —— 会话（一个 Slurm 作业）会结束，而数据要活过它。
 *
 * 于是每个插件都要回答三个问题：**跨版本共不共享**（`contributes.data`）、
 * **这一份数据要占几个本地端口**（`contributes.ports`）、**能不能同时开两份**
 * （`contributes.concurrent`）。三个都由**作者在清单里声明** —— 只有作者知道自己的
 * 新版本读不读得懂旧数据，也只有他知道自己的代码能不能同时处理两份。
 *
 * ── 两条轴、一个有缺省、一个没有 ────────────────────────────────────────────
 *
 *   身份 = <插件 id> / <共享组> / [<数据空间 id>]
 *
 *   · **共享组**：由作者声明，三态 —— `data.perVersion: true` ⇒ 这一格是**这个
 *     插件的版本号**（每个版本各一份）；`data.inherit` 写了共享组名 ⇒ 就是那个共享组名
 *     （几个版本写同一个共享组名 ⇒ 它们共用一份）；**两个都不写 ⇒ 常量 `DEFAULT_GROUP`**
 *     （所有版本共用一份）。两个都写是**矛盾**（一格说"共用"、一格说"各一份"），
 *     装的时候就拒，报错点名这两个键。
 *   · **数据空间**（第三段）：这个插件在**某一个工作区**里的那一份数据 ——
 *     一个本地端口、一份浏览器存储、一个插件数据目录。`contributes.ports` 大于 0 的
 *     插件才有这一段（要端口 = 要有 origin = 要有浏览器存储）；`ports: 0` ⇒
 *     **整段不存在**，那个插件整台机器上只有一份（sshd 那份就是 `<id>@relay`）。
 *     ★★ **它的取值必须两份不同**：同一个数据空间上并存两条会话，会让两份落在
 *     同一个目录里各写各的 ⇒ **静默损坏，而两边都以为自己成功了**。这条由运行期的
 *     槽闸守着（见 `slotOf`），而"第二份"由 `contributes.concurrent: true` 放行。
 *
 * ★★ **`concurrent` 管的是"能不能同时开第二份"，与"有没有第三段"是两件事** ——
 *   这一格的分工是 2026-10-09 那次重做定下来的。从前它兼着"有没有实例段"这个职责，
 *   于是一个**要端口、却声明不能多开**的插件（那是一句正常的声明：它只是不许
 *   同时开两份）整台机器上只有一份数据 —— 而它明明每个工作区里各有一份。
 *
 * ★★ **数据空间的 id 是「本机」的，所以整份身份不可跨机。** 它由这台客户端随机铸出
 *   （`config.js` 的 `newSpaceId`），两台电脑上"同一份数据"算出来的名字**不同**。
 *   今天没有后果 —— 这份数据本来就不出本机。但**哪天要做「运行时数据跟着用户走」**
 *   （多台客户端共享一份数据），这一条是必须先解决的前提：否则同步过去的那份数据
 *   **在每台机器上叫另一个名字**，而对账会把两边都判成孤儿（`plugin-data-audit.js`
 *   拿"该有的"做差，而"该有的"是按**当前**注册表加**本机**那份配置里的数据空间算的）。
 *   ★ 写在这里是因为**从代码上看不出这件事**：身份是算出来的，而算它的输入是本机的。
 *
 * ★★ **`ports` / `concurrent` 这两格的分工，判据不是"哪一格更安全"，是"这一格
 *   基座答得了吗"。**
 *
 *   · **要几个端口（=`ports`）：基座答得了** —— 它答的是"你的界面要几个 origin"，
 *     而那是一个事实。所以它有缺省（不写 = 0 = 不要数据空间）。
 *     ★ 它**是**个数、不是开关：一个数据空间带一份端口列表，列表多长由它说了算。
 *     今天框架只兑现得了 1 —— 一条会话只有一条隧道、作业侧只报得到一个候选端口，
 *     所以清单声明 2 是**一句框架做不到的话**。做不到的声明由 `plugins/index.js`
 *     在装之前**拒**掉，而不是收下之后只兑现第一个（那正是这个仓库一路在删的
 *     「配了但不生效」）。上界挪动时，盘上的形状不用动。
 *   · **共享组：两个方向基座都填得出来**（"共用一份"与"每个版本各一份"都是它能算
 *     的），所以它有缺省。缺省取哪边是一个**产品判断**，而它 2026-10-07 从"每个版本
 *     各一份"翻到了**继承**，理由：**没人管比读错更糟** —— 读错看得见（界面不对）、
 *     也修得好（删掉重配），而"每个版本悄悄攒一份没人再看过的数据"是**静默的**，
 *     并且会一直攒下去 —— 账本里那条「插件升过版本之后，回收算不出它留下的旧
 *     目录」记的就是它。
 *     ★ **代价如实记在这里**：缺省之下，一个**改过数据格式**的新版本会读到旧格式的
 *     东西。出路两条 —— 作者声明 `data.perVersion: true`，或者新版本自己判断读不读
 *     （它拿到的是路径，读不读由它定）。★ 再下一步是给数据加一个**格式版本**，让
 *     基座替作者判 —— 那一件还没做。
 *   · **能不能同时开两份（`concurrent`）：这一格基座答不了** —— 它答的是"你的代码
 *     能不能同时处理两份"，而那只有作者知道。缺省无论取哪一边都是基座替作者表态
 *     （取"不能"，一个真能多开的作者永远不知道为什么只能开一份；取"能"，一个没想过的
 *     作者会得到一个静默的第二份）⇒ 所以这一格**必填**，报错在 `plugins/index.js`。
 *
 * ★ **"共享"不是三选一的模式**，而是同一个声明写了什么：都写同一个共享组名 = 多对一；
 *   分组写 = 多组对多组；`perVersion` = 每个对每个；两个都不写 = 全员对一份。
 *   写成枚举就得额外回答"缺省是哪一个"，而那正是这个仓库一路在删的形状（要靠记才
 *   不搞错的东西）。★ 而 `perVersion` **不是**枚举里的第三个取值：它答的是**另一个
 *   问题**（第二段是不是版本号），与 `inherit`（第二段是哪一个共享组名）正交 —— 这正是
 *   它俩同时写就是矛盾的原因。
 *
 * ── 身份怎么变成一个落点 ────────────────────────────────────────────────────
 *
 * `identityOf` 给出的是**段的数组**，落点由读者各拼各的：
 *
 *   · 浏览器的存储分区 = `partitionOf(identity)` —— 段之间用 `@`，带 `persist:` 前缀
 *   · 分区目录的目录名 = `diskNameOf(identity)` —— 同一份身份，**折叠过**
 *   · 插件数据目录的目录名 = `dataDirNameOf(identity)` —— 同上，但**由我们拼**
 *
 * ★ 三个落点从**同一个身份**长出来，这是这个模块存在的全部理由：分别拼的话，
 *   "同一份数据"在分区名与目录名里会变成几个可以各自漂开的字符串。
 *
 * ★ 后两个**今天是同一个字符串**，而它们是两个函数：契约相反（见 `dataDirNameOf`
 *   的注释）。★ 它们**必须**同名 —— 对账把两个根放在一起做差，靠的就是"同一个身份
 *   在两个根下叫同一个名字"。
 *
 * ── ★ 运行期的那一半：`slotOf` ──────────────────────────────────────────────
 *
 * 上面三条回答的是"**一份数据**在哪儿"。同一个模块里还有一条**运行期**的规则，
 * 它回答的是"**一个活跃会话**占着什么"：**同一个槽同一时刻只能有一个活跃会话**
 * （`slotOf` 的注释里有逐条理由）。两者是同一件事的两面 —— 上面那条"同一个数据空间上
 * 并存两条会话，两份必然落在同一个目录里各写各的"说的是**数据**，`slotOf` 说的是**进程**。
 *
 * ── ★ 磁盘上的目录名与分区名的差别：折叠 ────────────────────────────────────
 *
 * Electron 44 的 `electron_browser_context.cc`：
 *
 *     MakePartitionName(input) = EscapePath(ToLowerASCII(input))
 *     path = PathService(DIR_SESSION_DATA) / "Partitions" / MakePartitionName(分区名去掉 'persist:')
 *
 * 也就是说**落盘时被 ASCII 折叠过**，而 `EscapePath` 的逃逸集里**没有 `@`**
 * （也没有 `.` `-`，逃的是 `#%:<>?[\]^`{|}` 与控制字符、非 ASCII）。两件事各有一个
 * 结论：
 *
 *   · 折叠只影响**插件 id** 那一段（ULID 是大写）—— 共享组与数据空间段的字符集本来就
 *     只允许小写，折不动。所以**磁盘上的名字与身份字符串只差 id 段的大小写**。
 *   · ★ 分隔符 `@` 能活着到磁盘上，不是猜的：它是上面那条 `EscapePath` 的直接推论。
 *
 * ★ 于是 `identityOfDiskName` 必须看**小写**的 ULID。而"比较"与"拼路径"要分清：
 *   折叠只用于**比较**（两边都折），路径一律由 `readdir` 拿到的**原始名字**拼 ——
 *   这样"Electron 折不折叠"两种情况下都对。
 *
 * ★ 另注：根是 `sessionData`（`app.getPath('sessionData')`），**不是 `userData`**。
 *   两者今天相同（没人调过 `app.setPath`），所以这是一处恰好对 —— 见
 *   plugin-data-audit.js 里那段注释，别顺手改成 `userData`。
 *
 * ── ★ 分隔符为什么是 `@` ────────────────────────────────────────────────────
 *
 * 分区名就是磁盘上的目录名（Electron 把 `persist:` 后面那一截当成存储目录，再折叠）。
 * 所以分隔符**不能**是 `/`，也不能是任何在某个平台上会被当成分隔符、或者会被
 * `EscapePath` 改写的东西。`@` 两个都不是，而且它在这个仓库里还有先例：信任台账的
 * `id@版本`、`once()` 的分桶键、会话的 `service_plugin` 解析键 —— 都是"两段身份拼成
 * 一个字符串"。
 *
 * ── ★ 段的字符集各由谁保证 ──────────────────────────────────────────────────
 *
 * 三段都进路径，而三段**各在自己的入口处**被查过，这里不重复查：
 *
 *   · 插件 id  —— `plugins/index.js` 的 `inspectDir`（必须是 26 字符的 ULID）；
 *   · 共享组   —— 同一处（`GROUP_RE`，就在下面）；
 *   · 数据空间 —— `config.js` 的 `normalizeSpace`（`SPACE_ID_RE`；`config.json`
 *                 是用户能手改的，所以那一格必须查）。
 *
 * ★ 在这里再查一遍是**不可观测的**冗余，而不可观测的防线会被当成防线 —— 见
 *   `plugins/index.js` 里 `parseVer` 那段同样的道理。三个入口各自的那条正则才是
 *   真正拦人的地方。
 *
 * ★ **共享组那一格的取值空间是两条正则的并**：`GROUP_RE` ∪ 版本号（`VERSION_RE`）。
 *   **声明的**那一侧只受 `GROUP_RE` 管，而**算出来的**那一侧是两者的并 ——
 *   `perVersion: true` 时那一格**就是**版本号。所以"第二段是共享组名还是版本号"这件事
 *   在字符串上**判不出来**（`1.0.0` 与一个共享组名同样合法），只能靠注册表里那个插件
 *   **当前**的版本号与它**声明的**那一格去对照才知道。`identityOfDiskName` 因此不猜
 *   这件事，只认"这一段是个像样的段"。
 *
 * ── 今天谁在用 ──────────────────────────────────────────────────────────────
 *
 * `partitionOf`：`index.js` 的 `ensureSurface`（建分区）与 `clearSpaceStorage`（回收）。
 * `diskNameOf` / `identityOfDiskName` / `hasSurface`：
 * `plugin-data-audit.js` 的对账（本机还剩几份、哪一份没人用）；`samePartition`：
 * 同一处的 `held`（"分区名与目录名是不是同一份"）。
 * `dataDirNameOf`：`index.js` 的 `ctx.dataDir()`（给插件一个落点）、
 * `snapshotTempData`（**临时那一份的起点快照** —— 它要从"持有者那一份"的目录名算出
 * 源路径），以及 `plugin-data-audit.js` 的对账（第二个根）。
 *
 * ★ **`dataDirNameOf` 在这里，是因为三条**同时**落了地：`ctx.dataDir()`、sshd
 *   搬进它、以及**对账长出第二个根**。任何一条单独做，它都会退回去变成一个没有
 *   读者的接口。
 *
 * ★ 对账那侧的口径：`plugin-data-audit.js` 里"该有哪些身份"的入口条件是
 *   **注册表里的所有插件**，而不是 `hasSurface`（**有没有界面**）—— 因为数据目录
 *   这第二个根不由框架建（`ensureSurface` 那种"不看声明就建"的推论在这里不成立），
 *   而是插件自己调 `ctx.dataDir()` 建出来的，数不出来。照 `hasSurface` 去算，
 *   **没有界面的 sshd 那份正在被用的数据一诞生就是孤儿**。放宽是安全方向
 *   （该有的变大 ⇒ 孤儿变少 ⇒ 删除按钮变少），而在分区那一侧**不改变任何行为**：
 *   多算出来的身份在磁盘上没有目录，不产生行。
 *
 * ── 词要钉住 ────────────────────────────────────────────────────────────────
 *
 * 这里一律写"**数据空间**"（第三段），而**数据空间由工作区里那张引用表指出来** ——
 * 「这个工作区把这个插件指到哪一份数据」正是用户自己选的"这几条连接共用一份"。
 * ★ 别写"这个工作区的那一份"：**一份数据可以被几个工作区同时引用**（那正是引用表
 * 存在的理由），说成"某个工作区的"会让"删掉一个工作区"看起来等于"删掉这份数据"。
 *
 * ★ 更别写"一条连接的那一份"：**一个数据空间不一定挂在任何一条连接上**
 *   （**临时那一份**就是这样的：它不属于任何工作区、也不属于任何连接，见 `index.js`
 *   的 `claimSpace`）。
 *
 * ★ **不要写"会话"**：那个词在代码里已经有主儿 = Slurm 作业（`session_id`、
 * `SessionController`、「开始会话」），写它会读岔 —— 而"每个会话有自己的配置"
 * 这句话按两种读法一对一错。
 */

const ulid = require('./plugins/ulid.js');

/**
 * 共享工作区的名字。
 *
 * 这是**作者写的字符串**，而它会进分区名 = 磁盘目录名 ⇒ 字符集必须受限。形状与
 * 清单里的 `name`（`plugins/index.js` 的 `NAME_RE`）**逐字相同**，因为两者要的是
 * 同一样东西：一个能安全地出现在路径、报错文案、日志里的短标识。
 *
 * ★ 两处**不合并成一条正则**：它们服务的是两件事（一个进配置文件名与会话文件，
 *   一个进分区名与目录名），而合并之后改动一边会静默地同时改另一边。
 */
const GROUP_RE = /^[a-z][a-z0-9-]{0,31}$/;

/**
 * 两个键都没写时，共享组那一格写**这个常量**。
 *
 * ★ 为什么是常量、又是为什么是这个字：第二段必须是一个能进路径、能进报错文案的
 *   短标识（同 `GROUP_RE` 管的那一格），而"所有版本共用一份"这件事只需要**一个
 *   名字**。取常量还有一层好处 —— 它与"作者显式写了这个名字"**同义**，于是"缺省"
 *   不是一种特殊状态，只是这个取值（没有 `data`、`data: null`、`data: {}` 全落在
 *   这里，没有第三档）。
 *
 * ★ 它**必须**匹配 `GROUP_RE`：这个名字会出现在磁盘目录名、报错文案与日志里，而
 *   `identityOfDiskName` 只认"像个样的段"。用例里有一条钉着它（改名改出格当场红）。
 */
const DEFAULT_GROUP = 'default';

// ── 大小写折叠：**ASCII-only** ──────────────────────────────────────────────
//
// ★ 它**住在这里**，因为它有两类消费者：
//
//   · §3.3 那条"同一个包里两条路径禁止只差大小写"（`COPY_SKIP` 在 plugins/index.js，
//     分发与读包都引它）；
//   · **身份字符串与磁盘上的名字之间的那道变换** —— 磁盘名是 `ToLowerASCII` 过的
//     （见文件头），所以"这件事在磁盘上叫什么"这个问题必须先折叠才答得了。
//
//   而 `plugins/index.js` 本来就 require 这个文件，所以折叠放在这一层、由那一层
//   re-export（`plugins.foldAscii` 的调用点一个都不用改）。反过来放就是循环 require。
//
// ★ 折叠**必须**只折叠 `A..Z`，**禁止**用 `String.prototype.toLowerCase()`：
//   后者是全 Unicode 的，会把 `İ`（U+0130）折成 `i̇`、把 `K`（U+212A KELVIN）
//   折成 `k` —— 于是两个实现可以在同一条路径上给出相反的答案，而这是一条
//   **拒绝**规则：一边收、一边拒，症状是"同一个包在一台机器上装得上、在另一台
//   上装不上"，而报错里一个字都不会提到大小写折叠。
//
// ★ ASCII-only 的折叠在 JS / Python / Node 打包器里逐字节相同：没有区域设置，
//   没有 Unicode 版本差异（`toLowerCase` 的结果会随 ICU 版本变）。它也与
//   Electron 那条 `base::ToLowerASCII` 逐字节同义 —— 这正是这里要它对齐的东西。
function foldAscii(s) {
  const t = typeof s === 'string' ? s : '';
  let out = '';
  for (let i = 0; i < t.length; i++) {
    const c = t.charCodeAt(i);
    out += c >= 0x41 && c <= 0x5a ? String.fromCharCode(c + 32) : t[i];
  }
  return out;
}

/**
 * 磁盘上那一段插件 id 的形状 —— **小写**的 ULID。
 *
 * ★ 字母表**从 `ulid.ENCODING` 派生**（折叠一次），不另抄一份：抄一份就会在字母表
 *   变动时静默漂开，而漂开的症状是"某一份数据认不出来"（它会被归进"认不出的目录"，
 *   于是一份本来该能删的数据永远删不掉）。
 */
const DISK_ID_RE = new RegExp(`^[${foldAscii(ulid.ENCODING)}]{26}$`);

/**
 * 插件 id 的**形状**（大写的 ULID）。
 *
 * ★ 与 `DISK_ID_RE` 同一份字母表、同样派生 —— 差别只在折叠与否。
 * ★ 它有一条**配置侧**的读者：`config.js` 的 `normalizeSpace`。数据空间那张表里存着
 *   插件 id，而它会走到磁盘路径里，`config.json` 又是用户能手改的 —— 那一格必须有人查，
 *   而查它的那条正则**只能有一份**。清单那一侧仍归 `plugins/index.js` 的 `inspectDir`。
 */
const PLUGIN_ID_RE = new RegExp(`^[${ulid.ENCODING}]{26}$`);

/** 插件清单里声明的那一段。**没写**与**写了但不是对象**在这里都是"没有声明" ——
 *  后者进不到这里（`inspectDir` 已经把它拒了），所以这不是一条防线，只是取值。 */
function dataOf(plugin) {
  const d = plugin && plugin.contributes && plugin.contributes.data;
  return d && typeof d === 'object' && !Array.isArray(d) ? d : null;
}

/**
 * 这个插件的这一份数据**要占几个本地端口** —— `contributes.ports` 那个数。
 *
 * ★ 判据只有一处。**别在别处内联读 `contributes.ports`** —— 内联一处，那一处就会在
 *   判据变动时漂开，而症状是"回收时认不出第三段" ⇒ **静默漏删**。
 *
 * ★ 它是**取值**不是**判定**（同 `groupOf` 的定位）：形状不对的（缺、非整数、负数）
 *   一律读成 0 —— 一份这样的清单进不到这里，`plugins/index.js` 在装之前就拒了。
 *   0 是"不要数据空间"这个正常状态，不是别名。
 *
 * ★ 运行时**只用得到前两个刻度**（0 = 不要，>0 = 要），所以这个数今天只被
 *   `needsSpace` 与 `config.js` 的建表用。上界夹在清单校验那一侧。
 */
function portCountOf(plugin) {
  const c = plugin && plugin.contributes;
  const n = c && c.ports;
  return Number.isInteger(n) && n > 0 ? n : 0;
}

/**
 * 这个插件的身份里**有没有第三段** —— 它要不要一个**数据空间**。
 *
 * ★ 判据只有一处：`portCountOf(plugin) > 0`（作者声明的"这份数据要几个端口"）。
 *   端口是数据空间之所以存在的东西（端口 = origin = 那份浏览器存储），所以这两件事
 *   是同一件，不是两条要各自维持的规矩。
 *
 * ★★ **它与 `canOpenSecond` 是两件事**，别合并：一个要端口、却声明不能同时开两份的
 *   插件照样有第三段（它在每个工作区里各有一份数据），只是那两份不能同时活着。
 *   ★ 从前这一格是 `concurrent` 说了算 —— 那是把"能不能同时开两份"当成了"有没有
 *   一份"，代价写在文件头。
 *
 * ★ 它是给**回收**那条路用的：一份数据被拆掉时，只有**按数据空间分**的那些插件
 *   才有"属于这一份"的存储要清。不按数据空间分的插件只有一份存储，它不属于任何
 *   数据空间，**绝不能跟着某一份一起被清掉**（sshd 那份 `<id>@relay` 就是）。
 */
function needsSpace(plugin) {
  return portCountOf(plugin) > 0;
}

/**
 * 这个插件**能不能同时开两份**。
 *
 * ★ 判据只有一处：`contributes.concurrent`。它管的是"第二份"这件事 —— 与
 *   "有没有第三段"（`needsSpace`）是两件不同的事，见文件头那一段。
 *
 * ★ 它只决定**认领**那一步给不给一份临时数据（见 `index.js` 的 `claimSpace`）：
 *   不能多开的插件恒拿到持有者那一份，于是槽闸照旧拒它并说出原因；能多开的拿到
 *   一份新的，于是两条并存。
 */
function canOpenSecond(plugin) {
  const c = plugin && plugin.contributes;
  return !!(c && c.concurrent === true);
}

/**
 * 这个插件的**共享组** —— 身份的第二段。
 *
 * ★ **只有这一处算它。** 三个落点都从 `identityOf` 长出来，而对账那张"该有的"表
 *   也走这里 —— 在别处再算一遍的话，两边会在清单声明的**意思**变动时漂开，症状是
 *   一份**活着的**数据被算成"不该有"，而界面上立刻多一个删除按钮。
 *
 * ★ 两个键同时写是**矛盾**，清单校验（`plugins/index.js`）在装之前就拒了。这里仍然
 *   让 `perVersion` 先判，是因为这一层的定位是**取值**而不是**判定**（见文件头
 *   "三段的字符集各由谁保证"那段）：在一份合法的清单上，两种写法不可能同时出现。
 *
 * ★ 它今天**不是**导出给生产代码用的（`identityOf` 是唯一入口）—— 导出是因为
 *   `plugin-data-audit.js` 要拿它写一句人能读的解释（"记的是 X，现在算出来是 Y"）。
 *   ★ 那句话**必须**由这里算，不能由那句文案自己拼：解释走一条跟判据不一样的路，
 *   就会出现"判对了、解释错了"。
 */
function groupOf(plugin) {
  const d = dataOf(plugin);
  if (d && d.perVersion === true) return plugin.version;
  return (d && typeof d.inherit === 'string' && d.inherit) || DEFAULT_GROUP;
}

/**
 * 一份数据的**身份**。
 *
 * @param {object} plugin  注册表里的插件对象（要 `id` / `version` / `contributes`）。
 *         给了那一份数据时它只用来判"这个插件要不要数据空间"（以及报错时点名）
 * @param {object} [space] 那一份数据（`config.js` 数据空间那一节里的形状）。
 *         `needsSpace` 为真的插件**必须**给出来
 * @returns {string[]} 不要数据空间是 `[id, 共享组]`；要数据空间是 `[插件 id, 共享组, 数据 id]`
 *
 * ★★ **有那一份数据时，三段全都取自它。** 这是那次重做的中心：
 *   `contributes.data.inherit` 声明的是"**哪些版本可以**共用一份"，而**实际用哪一份
 *   由用户那张引用表说了算**。取清单那一侧会有一种静默的失败 —— 作者改了共享组而
 *   引用表还没跟上的那段时间里，同一个插件会去读一个新路径，而数据在旧路径上
 *   （症状是"编辑器布局又重置了"，没有任何报错）。
 *   ★ 让两者对上的那条规矩只有一处：`config.js` 的 `spaceFor` —— 它发现记着的共享组
 *     与现在算出来的不一致时**新开一份**，而不是就地改名。
 *   ★ 而**不要数据空间的那些**（sshd）第二段仍然只能从清单来 —— 它们根本没有数据对象
 *     可问（那一份 `<id>@relay` 不属于任何工作区）。
 *
 * ★★ **它不需要注册表就答得了**（有那一份数据时）。这不是顺手得到的好处，而是
 *   回收那条路的**前提**：一份数据的主人被卸掉之后，注册表里没有它了，可盘上那份
 *   存储还得能算出名字来清掉。
 *
 * ★ 要数据空间却拿不到那一份时**抛**，不回落成两段：那会让**整台机器上这个插件**
 *   共用一份数据，而两边都以为自己写了 —— 正是这条轴要防的那件事，而它一旦发生是
 *   看不出来的（没有报错、没有异常，只有一份坏掉的数据）。
 *
 * ★ 这个抛**够得着**，而且今天就有两条路走到它旁边：
 *   · `ctx.dataDir()` 读的是 `rec.controller.spaceId`；`plugin.prepare()` 若跑在
 *     controller **构造之前**，一个「要数据空间 + 带 prepare」的插件提交就失败
 *     （见 index.js 里 startSession 的次序）；
 *   · `inspectDir` 已经拒了「能多开却一个端口都不要」的清单，`loadWorkspaces` 又保证
 *     每条连接都落在一个存在的工作区里，`spaceFor` 又保证那个工作区里这个插件有一份
 *     数据 —— 所以**走参数化调用的那几处**（`ensureSurface` / 对账）确实拿得到。
 *   留着它，是为了让"拿不到"有一个**说得出原因**的下场，而不是变成一句
 *   `Cannot read property of null`。
 */
function identityOf(plugin, space) {
  // ★ 有那一份数据时，**三段全从它自己来**（连插件 id 也是它记着的那个）——
  //   于是"一份数据叫什么名字"不需要注册表就答得了，而回收那条路正是这样：
  //   插件卸掉之后，注册表里已经没有它了，可盘上那份数据还得能算得出名字来。
  if (space) return [space.pluginId, space.group, space.id];
  if (needsSpace(plugin)) {
    throw new Error(
      `${(plugin && (plugin.name || plugin.id)) || '这个插件'} 声明了 `
      + `contributes.ports: ${portCountOf(plugin)}，但这次调用没有给出那一份数据。`
      + '第三段缺失时这个插件的每一份都会共用同一份数据，'
      + '而两边都以为自己写进去了 —— 那是一种看不出来的损坏，所以这里宁可停下来。'
      + '（那一份数据来自工作区里那张引用表：这就是要端口与要有第三段是同一件事的原因。）');
  }
  return [plugin.id, groupOf(plugin)];
}

/**
 * 这次会话占的那个**槽** —— 它拿走了哪一份「一个就够」的资源。
 *
 * ★ 这是运行期的不变量：**同一个槽同一时刻只能有一个活跃会话。**
 *   它是 `identityOf` 那条"同一个数据空间上并存两条会话，两份必然落在同一个目录里，
 *   各写各的"在**运行期**的对应物。
 *
 * ── 为什么只有两种槽 ────────────────────────────────────────────────────────
 *
 * `space:<数据空间 id>` —— 有数据空间的会话。一份数据 = 一个本地端口 = 一份 origin =
 *   一份浏览器存储 = 一个插件数据目录，所以**同一份数据上的第二个会话不行**：
 *   端口是同一个、分区也是同一个、目录还是同一个。
 *
 *   ★★ **槽按数据空间分，不按工作区分** —— 这是 2026-10-09 那次重做定下来的，而它
 *   换来的是**两个不同的插件可以在同一个工作区里同时活着**：数据是按插件分的，
 *   两个插件天然是两份数据 ⇒ 两个槽。从前槽名里带的是工作区 id，于是
 *   "同一个工作区的第二条会话"一律被拒 —— **哪怕它是另一个插件**，而那条拒绝
 *   自己写的理由两半都不成立：端口有 `excludedPortsFor` 排开，分区名里本来就
 *   带着插件 id。
 *
 * `relay` —— **全部**没有数据空间的会话，整类共用一个槽。★ 这一档**故意**粗。
 *   因为在这一类里，「互不干扰」不是基座保证的，而是**插件自己的口头承诺**：
 *   写进用户 ssh 配置的那个别名（`plugins/sshd/client/sshconfig.js` 的
 *   `SSH_ALIAS`）是插件自己的常量 —— 基座**无从核对**两个不要数据空间的插件的别名会不会撞。
 *   核对不了的事只能整类互斥：粗一档拒绝并说出原因，细一档（按插件 id 分槽）会让
 *   两个互不认识的不要数据空间的插件并存着去抢同一个别名，而症状是"`ssh slurmate` 连到
 *   哪一个是不确定的"，两边都报"已就绪"。
 *
 *   ★ **这一档粗的理由只剩别名这一半**：没有数据空间的会话的端口是基座给的常量
 *     （`RELAY_PORT_BASE`），基座**核对得了**，端口不构成"整类互斥"的理由。
 *     ★ 但**别**据此就把这一档按插件 id 拆细：拆细的前提是插件把别名也交给基座
 *     声明（让基座能核对并拒绝两个撞名的不要数据空间的插件），而那件事还没做。见账本。
 *
 * ★ **不要**在这里再补一条"数据身份"判据。它今天是上面两条的推论：有数据空间的会话
 *   必然同槽（**槽名带数据空间 id**），没有数据空间的会话只有 `relay` 一个槽。多一条
 *   判据就是多一个会漂的第二定义。
 *
 * ★★ **"第二份"不由这里放行，由 `claimSpace` 认领。** 走到这个函数时，那份临时
 *   数据的 id 已经是一个新的了（于是槽天然是两个：`space:sAA…` 与 `space:sBB…`）。
 *   这正是把槽名写成"带上那个 id"而不是"该不该有数据空间"换来的。
 *   ⇒ 下次再给数据空间开一个新来源时，**先问这一条还成不成立**，别默认它自动跟着变。
 *
 * @param {string|null} spaceId 这次会话的数据空间；不要数据空间的插件是 null
 * @returns {string} 槽的名字
 */
function slotOf(spaceId) {
  return spaceId ? `space:${spaceId}` : 'relay';
}

/**
 * 身份的**浏览器落点** —— Electron 的存储分区名。
 *
 * 结构是"每个插件一份，同一份身份共用"：`concurrent: true` 的插件，实例不同的
 * 两次会话拿到两个分区（于是能同时开）；不能多开的只有一份（于是两份会话写的是同一个
 * 目录 —— 那一格本来就不该同时开）。
 *
 * ★ 这是**给 Electron 用的名字**，不是磁盘上的目录名 —— 后者见 `diskNameOf`。
 */
function partitionOf(identity) {
  return 'persist:' + identity.join('@');
}

/**
 * 身份的**磁盘落点** —— Electron 写在 `<sessionData>/Partitions/` 下的那个目录名。
 *
 * ★ 与 `partitionOf` 只差两件事：**没有 `persist:` 前缀**、**ASCII 折叠过**
 *   （见文件头：`MakePartitionName`）。它只用来**比较**（两边都折），
 *   **绝不用来拼路径** —— 路径一律由 `readdir` 拿到的原始名字拼。
 */
function diskNameOf(identity) {
  return foldAscii(identity.join('@'));
}

/**
 * 身份的**插件数据落点** —— 基座给它建的那个目录名（`ctx.dataDir()` 就是它加上根）。
 *
 * ★ 三段用 `@` 拼成**一个名字**，**不是** `path.join(...identity)` 那样的三层目录。
 *   三层会让 `<id>/<共享组>` **既是两段身份的数据目录、又是三段身份的父目录** —— 而两份
 *   身份**真的会同时出现**：同一个插件 1.0.0 声明 `{inherit:'editor'}`（两段），
 *   2.0.0 声明 `{inherit:'editor', concurrent:true}`（三段），而 `inherit` 的语义
 *   恰恰是"这几个版本共享一份"。于是"删掉没人用的 editor 那一份"会把 2.0.0 那份
 *   **正在用的**连根 `rm -rf` 掉，而两边都不报错。单段名字让两份身份永远是**兄弟**，
 *   而这条不变量是"名字是单段"的直接推论，不需要任何检查去维持它。
 *
 * ★ 它今天是 `diskNameOf` 的**同值函数**（两个根下的同一个身份必须同名，对账的两个
 *   根共用一张"该有的"表靠的就是它），而**两个函数都要留**：契约相反 —— `diskNameOf`
 *   写着"**绝不**用来拼路径"（路径一律由 `readdir` 拿到的原始名拼），这一条**只用来
 *   拼路径**。合并之后"用谁拼路径"会在每个调用点重新回答一遍。
 *
 * ★ 于是这里**刻意重写一遍那个表达式、而不是转调 `diskNameOf`**：那样写的话"两者同值"
 *   会恒真，也就没有任何东西守着它；分开写，它是**可违约**的，而 `test/plugin-data.test.mjs`
 *   里那条等式会在有人只改一边时变红。
 */
function dataDirNameOf(identity) {
  return foldAscii(identity.join('@'));
}

/**
 * 磁盘上的目录名 → 身份的段。**认得出来才返回**，认不出来返回 `null`。
 *
 * ★ **它不是判据。** "这一份是不是孤儿"由 `plugin-data-audit.js` 拿"该有的集合"
 *   做差来判 —— 这个函数只用来**写一句人能读的解释**（"这是哪个插件的旧数据"），
 *   以及决定"这一行要不要给删除按钮"。★ 反过来做（拿它当判据）会把**活着的**分区
 *   判成垃圾：`identityOf` 的第二段可以是版本号，而磁盘名是折叠过的，两次变形叠加
 *   之后，"认不出来"与"是老垃圾"根本不是一回事。
 *
 * 判据只有两条：**第一段是（折叠过的）ULID**，段数 2 或 3。第二段**只要求非空** ——
 * 它可以是共享组名也可以是版本号，字符串上分不出来（见文件头那段）。
 *
 * @param {string} name 磁盘上的目录名（`readdir` 给的那个）
 * @returns {{id: string, group: string, instance: string|null}|null}
 *          `id` 是**折叠过**的那一份（磁盘上就是它）
 */
function identityOfDiskName(name) {
  if (typeof name !== 'string' || !name) return null;
  const parts = name.split('@');
  if (parts.length !== 2 && parts.length !== 3) return null;
  if (parts.some((p) => !p)) return null;
  if (!DISK_ID_RE.test(parts[0])) return null;
  return { id: parts[0], group: parts[1], instance: parts[2] || null };
}

/**
 * 这个插件会**在浏览器里建分区**吗 —— 判据只有一条：有没有界面。
 *
 * ★ 与上面那条**不是一回事**，别合并：没有界面就从来没有**分区**（`ensureSurface`
 *   第一行就返回了），所以它是"可能有一份数据"的入口条件；而"数据目录那个根要不要
 *   清"**不看这一条** —— 没有界面的插件照样可能在磁盘上留一份（见 `clearSpaceStorage`）。
 */
function hasSurface(plugin) {
  return !!(plugin && plugin.contributes && plugin.contributes.surface);
}

/**
 * 这个**分区**（`persist:…`，给 Electron 的名字）与磁盘上那个**目录名**是不是同一份。
 *
 * ★ 必须折叠后比：分区名里插件 id 那一段是大写的，而磁盘上那一段是小写的。拿两者
 *   直接 `===` 会**恒为假**，症状是"正被界面用着的那一份也被当成没人用" —— 而那正是
 *   最不能误判的一格（抽掉它的后果见 `index.js` 的 `clearSpaceStorage`）。
 *
 * ★ **唯一的调用者是 `plugin-data-audit.js` 的 `held`** —— 而它的用途正是"别把两个
 *   根各自的写法（分区名 vs 目录名）搞混"。★ 任何要判"这两串是不是同一份"的地方都
 *   应当调它，**不要**在别处再拼一遍 `persist:` 前缀：两条规矩会漂开，而漂开的症状是
 *   "护住活数据"在一半上静默失效。
 */
function samePartition(partition, diskName) {
  if (typeof partition !== 'string' || !partition.startsWith('persist:')) return false;
  if (typeof diskName !== 'string' || !diskName) return false;
  return foldAscii(partition.slice('persist:'.length)) === foldAscii(diskName);
}

